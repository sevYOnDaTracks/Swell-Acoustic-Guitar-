#!/usr/bin/env python3
"""Writes Source/Models.h from assets/samples/models.json (the built-in sample list).

models.json holds one entry per sample: type (0 acoustique, 1 electrique), display name,
FLAC path under assets/samples, root note (MIDI) and tuning offset in cents. Edit it to move
a sample to the other guitar or fix its tuning, then run: python3 Tools/models_header.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
models = json.load(open(os.path.join(here, '..', 'assets', 'samples', 'models.json'), encoding='utf-8'))
models.sort(key=lambda m: (m['type'], m['name'].lower()))
lines = ['#pragma once', '// Generated by Tools/models_header.py from assets/samples/models.json. Do not edit by hand.',
         '#include <array>', '',
         '// Built-in sample: guitar type, display name, embedded FLAC (file name), root note, tuning in cents.',
         'struct ModelInfo {int type;const char* name;const char* file;int root;float cents;};',
         f'inline constexpr int modelCount={len(models)};',
         'inline constexpr std::array<ModelInfo,modelCount> models{{']
lines += [f' {{{m["type"]},"{m["name"]}","{os.path.basename(m["file"])}",{m["root"]},{float(m["cents"]):.0f}.f}},' for m in models]
lines[-1] = lines[-1].rstrip(',')
lines += ['}};', '']
with open(os.path.join(here, '..', 'Source', 'Models.h'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print(len(models), 'models')
