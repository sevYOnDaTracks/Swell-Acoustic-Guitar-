#!/usr/bin/env python3
"""Writes Source/Models.h from assets/samples/models.json (the built-in guitar kits).

models.json holds one entry per kit: type (0 acoustique, 1 electrique), display name and kit
prefix. A kit is every embedded FLAC named <kit>_<note>_<layer>[_rrN].flac (see
Tools/prepare_kits.py). After changing it run: python3 Tools/models_header.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
models = json.load(open(os.path.join(here, '..', 'assets', 'samples', 'models.json'), encoding='utf-8'))
models.sort(key=lambda m: m['type'])
lines = ['#pragma once', '// Generated by Tools/models_header.py from assets/samples/models.json. Do not edit by hand.',
         '#include <array>', '',
         '// Built-in kit: guitar type, display name, prefix of its embedded FLAC files (<kit>_<note>_<layer>...).',
         'struct ModelInfo {int type;const char* name;const char* kit;};',
         f'inline constexpr int modelCount={len(models)};',
         'inline constexpr std::array<ModelInfo,modelCount> models{{']
lines += [f' {{{m["type"]},u8"{m["name"]}","{m["kit"]}"}},' for m in models]
lines[-1] = lines[-1].rstrip(',')
lines += ['}};', '']
with open(os.path.join(here, '..', 'Source', 'Models.h'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print(len(models), 'models')
